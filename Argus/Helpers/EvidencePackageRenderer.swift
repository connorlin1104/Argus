//
//  EvidencePackageRenderer.swift
//  Argus
//
//  Builds the Evidence Package PDF for one event: gathers the map snapshot,
//  video stills, and metadata into EvidenceReportData, then paginates the
//  EvidenceReportView blocks onto US Letter pages via ImageRenderer into a
//  CGContext PDF (vector text — selectable and small).
//
//  Failure policy: only PDF-context creation/write failures throw. The map
//  and stills degrade to omitted sections — a report with metadata and no
//  map is still useful evidence; no report at all is not.
//

import SwiftUI
import MapKit
import AVFoundation
import ImageIO
import UniformTypeIdentifiers
#if canImport(AppKit)
import AppKit
#endif

enum EvidencePackageRenderer {

    enum RenderError: LocalizedError {
        case pdfContextCreationFailed

        var errorDescription: String? {
            "Couldn't create the PDF file."
        }
    }

    // Page geometry: US Letter in PDF points.
    private static let pageSize = CGSize(width: 612, height: 792)
    private static let margin: CGFloat = 32
    private static var contentWidth: CGFloat { pageSize.width - margin * 2 }

    // TUNING: still size/quality inside the PDF. CGPDFContext stores
    // JPEG-sourced images as DCT streams, so these two knobs are what keep
    // a 4-still report well under 5 MB. Drop to 800 / 0.6 if files grow.
    private static let stillMaxPixels: CGFloat = 960
    private static let jpegQuality: CGFloat = 0.7

    // MARK: - Public API

    /// Gathers report data and writes the PDF to `url`.
    @MainActor
    static func writePDF(event: Event,
                         videos: [VideoRecording],
                         watchlist: [Watchlist],
                         to url: URL) async throws {
        let data = await buildData(event: event, videos: videos, watchlist: watchlist)
        try renderPDF(data: data, to: url)
    }

    /// "Evidence-2026-11-11-154217.pdf" — timestamped like the export
    /// folder names so a report is matchable to its event at a glance.
    static func pdfFileName(for event: Event) -> String {
        let fmt = DateFormatter()
        fmt.dateFormat = "yyyy-MM-dd-HHmmss"
        return "Evidence-\(fmt.string(from: event.timestamp)).pdf"
    }

    // MARK: - Data gathering

    @MainActor
    private static func buildData(event: Event,
                                  videos: [VideoRecording],
                                  watchlist: [Watchlist]) async -> EvidenceReportData {
        var metadata: [(label: String, value: String)] = []
        let camera = TeslaCamera.displayName(for: event.camera)
        if !camera.isEmpty { metadata.append(("Camera", camera)) }
        if !event.city.isEmpty { metadata.append(("City", event.city)) }
        if !event.address.isEmpty { metadata.append(("Address", event.address)) }
        metadata.append(("Latitude", event.estLatitude))
        metadata.append(("Longitude", event.estLongitude))
        if !event.reason.isEmpty {
            metadata.append(("Trigger", EventSummarizer.humanizeReason(event.reason)))
        }
        if event.tag != "unknown" { metadata.append(("Behavior", event.tag.capitalized)) }
        if event.interestingnessScore > 0 {
            metadata.append(("Activity", ScoreBadge.label(for: event.interestingnessScore)))
        }
        if !event.zone.isEmpty { metadata.append(("Zone", event.zone)) }

        let matches = WatchlistMatcher.matches(event: event, in: watchlist)
            .map { ($0.entry.plateText, $0.entry.note, $0.isExact, $0.entry.colorHex) }
        let plateReads = event.plateText.split(separator: " ").map(String.init)

        return EvidenceReportData(
            title: EventMiniMapSection.displayName(for: event),
            timestamp: event.timestamp,
            cameraName: camera,
            trigger: event.reason.isEmpty ? "" : EventSummarizer.humanizeReason(event.reason),
            mapImage: await mapSnapshot(for: event),
            summary: event.summary,
            notes: event.notes,
            stills: await extractStills(videos: videos),
            metadata: metadata,
            watchlistMatches: matches,
            plateReads: plateReads,
            hadClips: !videos.isEmpty,
            footer: "Generated by Argus on \(Date().formatted(date: .long, time: .shortened))"
        )
    }

    /// Map snapshot with a pin composited at the event location. Nil when
    /// the event has no valid coordinates or the snapshot fails (offline) —
    /// the report just omits the map section.
    private static func mapSnapshot(for event: Event) async -> CGImage? {
        guard let coord = EventMiniMapSection.validCoord(latString: event.estLatitude,
                                                         lonString: event.estLongitude) else {
            return nil
        }
        let options = MKMapSnapshotter.Options()
        // Same span as the live mini-map so the printed context matches
        // what the user sees in the app.
        options.region = MKCoordinateRegion(
            center: coord,
            span: MKCoordinateSpan(latitudeDelta: 0.008, longitudeDelta: 0.008)
        )
        options.size = CGSize(width: contentWidth, height: 220)
        guard let snapshot = try? await MKMapSnapshotter(options: options).start() else {
            return nil
        }
        return compositePin(on: snapshot, at: coord)
    }

    /// MKMapSnapshotter doesn't render annotations — draw the event pin
    /// ourselves on top of the snapshot image.
    private static func compositePin(on snapshot: MKMapSnapshotter.Snapshot,
                                     at coord: CLLocationCoordinate2D) -> CGImage? {
        #if canImport(AppKit)
        var proposedRect = CGRect(origin: .zero, size: snapshot.image.size)
        guard let base = snapshot.image.cgImage(forProposedRect: &proposedRect,
                                                context: nil, hints: nil) else { return nil }
        #else
        guard let base = snapshot.image.cgImage else { return nil }
        #endif
        guard let space = CGColorSpace(name: CGColorSpace.sRGB),
              let ctx = CGContext(data: nil,
                                  width: base.width, height: base.height,
                                  bitsPerComponent: 8, bytesPerRow: 0,
                                  space: space,
                                  bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) else {
            return base
        }
        ctx.draw(base, in: CGRect(x: 0, y: 0, width: base.width, height: base.height))

        // point(for:) is in the image's native coordinate space: top-left
        // origin with UIKit, bottom-left with AppKit — flip for CG on iOS.
        let point = snapshot.point(for: coord)
        let scaleX = CGFloat(base.width) / snapshot.image.size.width
        let scaleY = CGFloat(base.height) / snapshot.image.size.height
        let px = point.x * scaleX
        #if canImport(AppKit)
        let py = point.y * scaleY
        #else
        let py = CGFloat(base.height) - point.y * scaleY
        #endif
        let radius = 6 * scaleX
        let dot = CGRect(x: px - radius, y: py - radius, width: radius * 2, height: radius * 2)
        ctx.setFillColor(CGColor(red: 1, green: 0.23, blue: 0.19, alpha: 1))
        ctx.fillEllipse(in: dot)
        ctx.setStrokeColor(CGColor(red: 1, green: 1, blue: 1, alpha: 1))
        ctx.setLineWidth(1.5 * scaleX)
        ctx.strokeEllipse(in: dot)
        return ctx.makeImage()
    }

    /// Extract the frames EventStillPicker chose, in pick order (the human
    /// moment leads). One generator per clip, security scope held for the
    /// whole extraction.
    private static func extractStills(videos: [VideoRecording]) async -> [(image: CGImage, caption: String)] {
        let picks = EventStillPicker.pick(clips: videos.enumerated().map {
            EventStillPicker.ClipMarkers(clipIndex: $0.offset, markers: $0.element.markers)
        })
        guard !picks.isEmpty else { return [] }

        var generators: [Int: AVAssetImageGenerator] = [:]
        var accessedURLs: [URL] = []
        defer { for url in accessedURLs { url.stopAccessingSecurityScopedResource() } }

        var stills: [(image: CGImage, caption: String)] = []
        for still in picks {
            let video = videos[still.clipIndex]
            let generator: AVAssetImageGenerator
            if let existing = generators[still.clipIndex] {
                generator = existing
            } else {
                guard let url = BookmarkResolver.resolveURL(for: video) else { continue }
                if url.startAccessingSecurityScopedResource() { accessedURLs.append(url) }
                let fresh = AVAssetImageGenerator(asset: AVURLAsset(url: url))
                fresh.appliesPreferredTrackTransform = true
                fresh.maximumSize = CGSize(width: stillMaxPixels, height: stillMaxPixels)
                // Loose tolerance: the nearest keyframe is fine for a still
                // and avoids decoding from the clip's start for every frame.
                fresh.requestedTimeToleranceBefore = CMTime(value: 1, timescale: 2)
                fresh.requestedTimeToleranceAfter = CMTime(value: 1, timescale: 2)
                generators[still.clipIndex] = fresh
                generator = fresh
            }
            let time = CMTime(value: CMTimeValue(still.timestampMs), timescale: 1000)
            guard let (image, _) = try? await generator.image(at: time) else { continue }
            let caption = EventStillPicker.caption(cameraID: video.camera,
                                                   clipStart: video.startTime,
                                                   offsetMs: still.timestampMs)
            stills.append((jpegCompressed(image), caption))
        }
        return stills
    }

    /// JPEG round-trip so CGPDFContext embeds the frame as a DCT stream
    /// (~150–400 KB) instead of lossless Flate (1–2 MB per frame). Returns
    /// the original image if anything in the round-trip fails.
    private static func jpegCompressed(_ image: CGImage) -> CGImage {
        let data = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(
            data, UTType.jpeg.identifier as CFString, 1, nil) else { return image }
        CGImageDestinationAddImage(dest, image, [
            kCGImageDestinationLossyCompressionQuality: jpegQuality
        ] as CFDictionary)
        guard CGImageDestinationFinalize(dest),
              let source = CGImageSourceCreateWithData(data, nil),
              let compressed = CGImageSourceCreateImageAtIndex(source, 0, nil) else {
            return image
        }
        return compressed
    }

    // MARK: - Pagination

    /// Render each report block in order, flowing top-down onto US Letter
    /// pages; a block that doesn't fit the remaining space starts a new
    /// page. The PDF context's origin is bottom-left, so the top-down
    /// cursor translates to y = cursor - blockHeight before each draw.
    @MainActor
    private static func renderPDF(data: EvidenceReportData, to url: URL) throws {
        var mediaBox = CGRect(origin: .zero, size: pageSize)
        guard let consumer = CGDataConsumer(url: url as CFURL),
              let pdf = CGContext(consumer: consumer, mediaBox: &mediaBox, nil) else {
            throw RenderError.pdfContextCreationFailed
        }

        let pageTop = pageSize.height - margin
        pdf.beginPDFPage(nil)
        var cursorY = pageTop
        for block in EvidenceReportBlock.blocks(for: data) {
            let renderer = ImageRenderer(content:
                EvidenceReportBlock.view(block, data: data)
                    .frame(width: contentWidth)
            )
            renderer.proposedSize = ProposedViewSize(width: contentWidth, height: nil)
            renderer.render { size, draw in
                // New page when the block overflows the remaining space —
                // unless the page is empty (a block taller than a full page
                // draws clipped rather than looping forever).
                if cursorY - size.height < margin, cursorY < pageTop {
                    pdf.endPDFPage()
                    pdf.beginPDFPage(nil)
                    cursorY = pageTop
                }
                pdf.saveGState()
                pdf.translateBy(x: margin, y: cursorY - size.height)
                draw(pdf)
                pdf.restoreGState()
                cursorY -= size.height
            }
        }
        pdf.endPDFPage()
        pdf.closePDF()
    }
}
